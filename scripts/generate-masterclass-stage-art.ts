import fs from 'node:fs';
// Run with: npx tsx scripts/generate-masterclass-stage-art.ts
// Reuses trusted local drawings, keeps their full reference, adds a moving stroke overlay.
const drawings:Record<string,string>={};
for(const file of fs.readdirSync('public/images/masterclass').filter(name=>name.endsWith('.svg')).sort()){
 const key=file.replace(/\.svg$/,'');
 let svg=fs.readFileSync(`public/images/masterclass/${file}`,'utf8').replace(/<style>[\s\S]*?<\/style>/g,'');
 svg=svg.replace('<svg ','<svg translate="no" lang="en" ').replaceAll('id="tip"',`id="mc-stage-tip-${key}"`).replaceAll('url(#tip)',`url(#mc-stage-tip-${key})`);
 svg=svg.replace(/(<path\b[^>]*class="(?:price|bear-line|arrow|quiet)"[^>]*\/>)/g,path=>path+path.replace('class="','pathLength="1" class="mc-trace '));
 drawings[key]=svg;
}
fs.writeFileSync('src/data/masterclassStageArt.ts','// Generated by scripts/generate-masterclass-stage-art.ts from trusted local SVGs.\nexport const masterclassStageArt:Record<string,string>='+JSON.stringify(drawings)+';\n');
console.log(`Stage geometry: ${Object.keys(drawings).length} local drawings, including neutral fallback.`);
